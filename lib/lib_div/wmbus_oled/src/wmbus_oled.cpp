// SSD1306 command opcodes used in the init sequence.
constexpr uint8_t kCmdDisplayOff       = 0xAE;
constexpr uint8_t kCmdDisplayOn        = 0xAF;
constexpr uint8_t kCmdSetDisplayClock  = 0xD5;
constexpr uint8_t kCmdSetMultiplex     = 0xA8;
constexpr uint8_t kCmdSetDisplayOffset = 0xD3;
constexpr uint8_t kCmdSetStartLine     = 0x40;
constexpr uint8_t kCmdChargePump       = 0x8D;
constexpr uint8_t kCmdMemoryMode       = 0x20;
constexpr uint8_t kCmdSegRemap         = 0xA1;   // column 127 mapped to SEG0
constexpr uint8_t kCmdComScanDec       = 0xC8;
constexpr uint8_t kCmdSetComPins       = 0xDA;
constexpr uint8_t kCmdSetContrast      = 0x81;
constexpr uint8_t kCmdSetPrecharge     = 0xD9;
constexpr uint8_t kCmdSetVComDetect    = 0xDB;
constexpr uint8_t kCmdDisplayAllOnResume = 0xA4;
constexpr uint8_t kCmdNormalDisplay    = 0xA6;
constexpr uint8_t kCmdDeactivateScroll = 0x2E;
constexpr uint8_t kCmdColumnAddr       = 0x21;
constexpr uint8_t kCmdPageAddr         = 0x22;

